-- ====================================================
-- SCRIPT 02: TẠO CẤU TRÚC BẢNG VÀ INDEX
-- ====================================================

-- 1. TẠO CÁC BẢNG (TABLES)
CREATE TABLE BanAn (
                       MaBan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       MaBanCode VARCHAR(20) NOT NULL UNIQUE,
                       TenBan VARCHAR(50) NOT NULL,
                       SucChua INT NOT NULL,
                       TrangThai VARCHAR(50) NOT NULL DEFAULT 'EMPTY',
                       DangSuDung BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE NhanVien (
                          MaNhanVien BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          MaNhanVienCode VARCHAR(20) NOT NULL UNIQUE,
                          HoTen VARCHAR(100) NOT NULL,
                          SoDienThoai VARCHAR(20),
                          TenDangNhap VARCHAR(50) NOT NULL UNIQUE,
                          MatKhau VARCHAR(255) NOT NULL,
                          VaiTro VARCHAR(50) NOT NULL,
                          DangLamViec BOOLEAN NOT NULL DEFAULT TRUE,
                          DaNghiViec BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE LoaiMon (
                         MaLoaiMon BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         TenLoaiMon VARCHAR(100) NOT NULL,
                         MoTa TEXT
);

CREATE TABLE MonAn (
                       MaMon BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       MaLoaiMon BIGINT NOT NULL,
                       MaMonCode VARCHAR(30) NOT NULL UNIQUE,
                       TenMon VARCHAR(150) NOT NULL,
                       DonGia DECIMAL(15,2) NOT NULL,
                       HinhAnh VARCHAR(255),
                       MoTa TEXT,
                       DangKinhDoanh BOOLEAN NOT NULL DEFAULT TRUE,
                       CONSTRAINT fk_monan_loaimon
                           FOREIGN KEY (MaLoaiMon) REFERENCES LoaiMon(MaLoaiMon)
                               ON UPDATE CASCADE
                               ON DELETE RESTRICT
);

CREATE TABLE GhiChuMon (
                           MaGhiChu BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           MaMon BIGINT NOT NULL,
                           NoiDungGhiChu VARCHAR(100) NOT NULL,
                           CONSTRAINT fk_ghichumon_monan
                               FOREIGN KEY (MaMon) REFERENCES MonAn(MaMon)
                                   ON UPDATE CASCADE
                                   ON DELETE CASCADE
);

CREATE TABLE DonHang (
                         MaDonHang BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         SoDonHang VARCHAR(50) NOT NULL UNIQUE,
                         MaBan BIGINT NOT NULL,
                         MaNhanVien BIGINT NOT NULL,
                         ThoiGianLap TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                         TongTien DECIMAL(15,2) NOT NULL DEFAULT 0,
                         TrangThai VARCHAR(50) NOT NULL,
                         GhiChu TEXT,
                         CONSTRAINT fk_donhang_banan
                             FOREIGN KEY (MaBan) REFERENCES BanAn(MaBan)
                                 ON UPDATE CASCADE
                                 ON DELETE RESTRICT,
                         CONSTRAINT fk_donhang_nhanvien
                             FOREIGN KEY (MaNhanVien) REFERENCES NhanVien(MaNhanVien)
                                 ON UPDATE CASCADE
                                 ON DELETE RESTRICT
);

CREATE TABLE ChiTietDonHang (
                                MaChiTiet BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                MaDonHang BIGINT NOT NULL,
                                MaMon BIGINT NOT NULL,
                                SoLuong INT NOT NULL,
                                DonGia DECIMAL(15,2) NOT NULL,
                                ThanhTien DECIMAL(15,2) NOT NULL,
                                GhiChu TEXT,
                                CONSTRAINT fk_ctdh_donhang
                                    FOREIGN KEY (MaDonHang) REFERENCES DonHang(MaDonHang)
                                        ON UPDATE CASCADE
                                        ON DELETE CASCADE,
                                CONSTRAINT fk_ctdh_monan
                                    FOREIGN KEY (MaMon) REFERENCES MonAn(MaMon)
                                        ON UPDATE CASCADE
                                        ON DELETE RESTRICT
);

CREATE TABLE HoaDon (
                        MaHoaDon BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        SoHoaDon VARCHAR(50) NOT NULL UNIQUE,
                        MaDonHang BIGINT NOT NULL UNIQUE,
                        ThoiGianThanhToan TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                        TongTien DECIMAL(15,2) NOT NULL,
                        PhuongThucThanhToan VARCHAR(50) NOT NULL,
                        CONSTRAINT fk_hoadon_donhang
                            FOREIGN KEY (MaDonHang) REFERENCES DonHang(MaDonHang)
                                ON UPDATE CASCADE
                                ON DELETE RESTRICT
);

-- 2. TẠO INDEX (TỐI ƯU TRUY VẤN)
CREATE INDEX idx_banan_trangthai ON BanAn(TrangThai);
CREATE INDEX idx_banan_dangsudung ON BanAn(DangSuDung);
CREATE INDEX idx_nhanvien_vaitro ON NhanVien(VaiTro);
CREATE INDEX idx_nhanvien_trangthai ON NhanVien(DangLamViec, DaNghiViec);
CREATE INDEX idx_monan_loaimon ON MonAn(MaLoaiMon);
CREATE INDEX idx_monan_dangkinhdoanh ON MonAn(DangKinhDoanh);
CREATE INDEX idx_ghichumon_mamon ON GhiChuMon(MaMon);
CREATE INDEX idx_donhang_ban_trangthai ON DonHang(MaBan, TrangThai);
CREATE INDEX idx_donhang_thoigianlap ON DonHang(ThoiGianLap);
CREATE INDEX idx_donhang_nhanvien ON DonHang(MaNhanVien);
CREATE INDEX idx_ctdh_donhang ON ChiTietDonHang(MaDonHang);
CREATE INDEX idx_ctdh_monan ON ChiTietDonHang(MaMon);
CREATE INDEX idx_hoadon_thoigianthanhtoan ON HoaDon(ThoiGianThanhToan);